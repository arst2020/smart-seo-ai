	}

	private static function contact_info() {
		$e    = SSAI_SEO::get( 'entity' );
		$addr = trim( implode( '، ', array_filter( array( $e['street'], $e['city'], $e['region'] ) ) ) );
		return array(
			'name'    => '' !== $e['name'] ? $e['name'] : get_bloginfo( 'name' ),
			'phone'   => $e['phone'],
			'email'   => $e['email'],
			'address' => $addr,
			'hours'   => $e['hours'],
			'lat'     => $e['lat'],
			'lng'     => $e['lng'],
		);
	}

	private static function cta_link() {
		$b = SSAI_Studio::brand();
		if ( '' !== $b['cta_url'] ) {
			return $b['cta_url'];
		}
		foreach ( array( 'contact-us', 'contact', 'تماس-با-ما' ) as $slug ) {
			$p = get_page_by_path( $slug );
			if ( $p ) {
				return get_permalink( $p );
			}
		}
		$c = self::contact_info();
		return '' !== $c['phone'] ? 'tel:' . preg_replace( '/[^\d+]/', '', $c['phone'] ) : home_url( '/' );
	}

	/* ================================================================ Clean data */

	private static function clean_text( $s ) {
		return trim( wp_strip_all_tags( preg_replace( '/\[\[\s*(?:REVIEW|بررسی|CHECK)\s*:?\s*(.*?)\]\]/iu', '[نیاز به بررسی: $1]', (string) $s ) ) );
	}

	private static function clean_blocks( $list, $from_ai = false ) {
		$lib  = self::blocks();
		$out  = array();
		$pages = $from_ai ? array_flip( array_map( 'intval', array_keys( self::site_pages() ) ) ) : null;
		foreach ( (array) $list as $b ) {
			if ( ! is_array( $b ) || empty( $b['type'] ) || ! isset( $lib[ $b['type'] ] ) ) {
				continue;
			}
			$t = $b['type'];
			if ( $from_ai && 'testimonials' === $t ) {
				continue; // Reviews are never written by the AI.
			}
			$items = array();
			foreach ( isset( $b['items'] ) && is_array( $b['items'] ) ? $b['items'] : array() as $it ) {
				if ( ! is_array( $it ) ) {
					$it = array( 'text' => (string) $it );
				}
				$icon = isset( $it['icon'] ) ? strtolower( trim( (string) $it['icon'] ) ) : '';
				$icon = preg_match( '/(?:^|\s)fa-([a-z0-9-]+)\s*$/', $icon, $im ) ? $im[1] : sanitize_key( $icon ); // "fas fa-award" → "award".
				$link = isset( $it['page_id'] ) ? (int) $it['page_id'] : ( isset( $it['link'] ) ? (int) $it['link'] : 0 );
				if ( $link && ( ( null !== $pages && ! isset( $pages[ $link ] ) ) || 'publish' !== get_post_status( $link ) ) ) {
					$link = 0; // Only real, published pages.
				}
				$text = 'faq' === $t || 'intro' === $t ? SSAI_Studio::clean_html( isset( $it['text'] ) ? (string) $it['text'] : '' ) : self::clean_text( isset( $it['text'] ) ? $it['text'] : '' );
				$items[] = array(
					'title' => self::clean_text( isset( $it['title'] ) ? $it['title'] : '' ),
					'text'  => $text,
					'icon'  => in_array( $icon, self::icons(), true ) ? $icon : 'check',
					'link'  => $link,
				);
			}
			$images = array();
			foreach ( isset( $b['images'] ) && is_array( $b['images'] ) ? $b['images'] : array() as $iid ) {
				if ( wp_attachment_is_image( (int) $iid ) ) {
					$images[] = (int) $iid;
				}
			}
			$img = isset( $b['image'] ) ? (int) $b['image'] : 0;
			$out[] = array(
				'type'   => $t,
				'title'  => self::clean_text( isset( $b['title'] ) ? $b['title'] : '' ),
				'text'   => in_array( $t, array( 'intro', 'contact' ), true ) ? SSAI_Studio::clean_html( isset( $b['text'] ) ? (string) $b['text'] : '' ) : self::clean_text( isset( $b['text'] ) ? $b['text'] : '' ),
				'button' => self::clean_text( isset( $b['button'] ) ? $b['button'] : '' ),
				'image'  => $img && wp_attachment_is_image( $img ) ? $img : 0,
				'images' => array_slice( $images, 0, 12 ),
				'items'  => array_slice( $items, 0, 8 ),
				'map'    => ! empty( $b['map'] ) ? 1 : 0,
				'form'   => ! empty( $b['form'] ) ? 1 : 0,
			);
		}
		return array_slice( $out, 0, 14 );
	}

	/** Published pages the services cards may link to. */
	private static function site_pages() {
		$out = array();
		foreach ( get_posts( array( 'post_type' => 'page', 'post_status' => 'publish', 'posts_per_page' => 80, 'orderby' => 'menu_order title', 'order' => 'ASC' ) ) as $p ) {
			$out[ $p->ID ] = get_the_title( $p );
		}
		return $out;
	}

	/** Real posts for the "related posts" block (by keyword, else latest). */
	private static function related_posts( $m, $n = 3 ) {
		$q = get_posts( array( 'post_type' => 'post', 'post_status' => 'publish', 'posts_per_page' => $n, 's' => '' !== $m['keyword'] ? $m['keyword'] : $m['topic'] ) );
		if ( ! $q ) {
			$q = get_posts( array( 'post_type' => 'post', 'post_status' => 'publish', 'posts_per_page' => $n ) );
		}
		return $q;
	}

	/* ================================================================ AJAX */

	private static function item_or_new() {
		$id = isset( $_POST['item'] ) ? absint( $_POST['item'] ) : 0; // phpcs:ignore WordPress.Security.NonceVerification
		if ( $id ) {
			return SSAI_Studio::req_item();
		}
		return wp_parse_args(
			array(
				'type'    => 'design',
				'kind'    => 'service',
				'builder' => key( self::builders() ) ? key( self::builders() ) : 'elementor',
				'blocks'  => array(),
				'source_page' => 0,
				'facts'   => '',
				'form_code' => '',
			),
			array( 'type' => 'design', 'topic' => '', 'keyword' => '', 'title' => '', 'notes' => '', 'lang' => '', 'audience' => '', 'seo' => array( 'seo_title' => '', 'meta' => '', 'slug' => '', 'keywords' => array() ), 'status' => 'idea', 'post_id' => 0, 'date' => '', 'outline' => array(), 'sections' => array(), 'target' => 0, 'length' => 'medium', 'secondary' => '' )
		);
	}

	private static function read_brief( $m ) {
		foreach ( array( 'topic', 'keyword', 'title' ) as $k ) {
			if ( isset( $_POST[ $k ] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
				$m[ $k ] = SSAI_Studio::txt( $k );
			}
		}
		foreach ( array( 'facts', 'notes' ) as $k ) {
			if ( isset( $_POST[ $k ] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
				$m[ $k ] = mb_substr( SSAI_Studio::txt( $k, true ), 0, 4000 );
			}
		}
		if ( isset( $_POST['form_code'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$fc             = SSAI_Studio::txt( 'form_code' );
			$m['form_code'] = preg_match( '/^\[[a-z0-9_\-]+[^\]]*\]$/i', $fc ) ? $fc : '';
		}
		if ( isset( $_POST['kind'] ) && isset( self::kinds()[ SSAI_Studio::txt( 'kind' ) ] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$m['kind'] = SSAI_Studio::txt( 'kind' );
		}
		if ( isset( $_POST['builder'] ) && isset( self::builders()[ SSAI_Studio::txt( 'builder' ) ] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$m['builder'] = SSAI_Studio::txt( 'builder' );
		}
		if ( isset( $_POST['source_page'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$sp               = absint( $_POST['source_page'] ); // phpcs:ignore WordPress.Security.NonceVerification
			$m['source_page'] = $sp && current_user_can( 'edit_post', $sp ) ? $sp : 0;
		}
		if ( isset( $_POST['blocks'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$bl = json_decode( wp_unslash( $_POST['blocks'] ), true ); // phpcs:ignore WordPress.Security.NonceVerification, WordPress.Security.ValidatedSanitizedInput
			if ( is_array( $bl ) ) {
				$m['blocks'] = self::clean_blocks( $bl );
			}
		}
		if ( isset( $_POST['seo'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$seo = json_decode( wp_unslash( $_POST['seo'] ), true ); // phpcs:ignore WordPress.Security.NonceVerification, WordPress.Security.ValidatedSanitizedInput
			if ( is_array( $seo ) ) {
				$m['seo'] = array(
					'seo_title' => isset( $seo['seo_title'] ) ? sanitize_text_field( (string) $seo['seo_title'] ) : '',
					'meta'      => isset( $seo['meta'] ) ? sanitize_textarea_field( (string) $seo['meta'] ) : '',
					'slug'      => isset( $seo['slug'] ) ? sanitize_title( (string) $seo['slug'] ) : '',
					'keywords'  => array_values( array_filter( array_map( 'sanitize_text_field', (array) ( isset( $seo['keywords'] ) ? $seo['keywords'] : array() ) ) ) ),
				);
			}
		}
		if ( '' === $m['topic'] && ! $m['source_page'] ) {
			$m['topic'] = get_bloginfo( 'name' );
		}
		return $m;
	}

	private static function out( $m ) {
		$m['preview'] = self::preview( $m );
		$m['marks']   = substr_count( $m['preview'], 'نیاز به بررسی' );
		foreach ( $m['blocks'] as $i => $b ) {
			$m['blocks'][ $i ]['image_url'] = $b['image'] ? (string) wp_get_attachment_image_url( $b['image'], 'thumbnail' ) : '';
			$m['blocks'][ $i ]['image_urls'] = array_map(
				function ( $id ) {
					return (string) wp_get_attachment_image_url( $id, 'thumbnail' );
				},
				$b['images']
			);
		}
		$m['edit_url'] = $m['post_id'] ? ( 'elementor' === $m['builder'] ? SSAI_Elementor::edit_url( $m['post_id'] ) : get_edit_post_link( $m['post_id'], 'raw' ) ) : '';
		$m['view_url'] = $m['post_id'] ? get_preview_post_link( $m['post_id'] ) : '';
		return $m;
	}

	public static function ajax_get() {
		SSAI_Studio::guard();
		wp_send_json_success( array( 'item' => self::out( SSAI_Studio::req_item() ) ) );
	}

	public static function ajax_save() {
		SSAI_Studio::guard();
		$m = self::read_brief( self::item_or_new() );
		$m = SSAI_Studio::store( $m );
		if ( is_wp_error( $m ) ) {
			wp_send_json_error( array( 'message' => $m->get_error_message() ) );
		}
		wp_send_json_success( array( 'item' => self::out( SSAI_Studio::item( $m['id'] ) ), 'message' => 'ذخیره شد.' ) );
	}

	/** AI: choose blocks and write their texts. */
	public static function ajax_plan() {
		SSAI_Studio::guard();
		$m = self::read_brief( self::item_or_new() );
		SSAI_Studio::lock();
		$lib = array();
		foreach ( self::blocks() as $k => $b ) {
			if ( 'testimonials' !== $k ) {
				$lib[ $k ] = $b[1];
			}
		}
		$src = null;
		if ( $m['source_page'] ) {
			$d = SSAI_Content::data( $m['source_page'] );
			if ( $d ) {
				$src = array( 'title' => $d['title'], 'text' => mb_substr( $d['text'], 0, 6000 ) );
				if ( '' === $m['keyword'] ) {
					$m['keyword'] = $d['focus_keyword'];
				}
			}
		}
		$pages = array();
		foreach ( self::site_pages() as $id => $t ) {
			$pages[] = array( 'page_id' => $id, 'title' => $t );
		}
		$suggest = array(
			'service' => 'hero, features, intro, benefits, steps, faq, cta, contact',
			'home'    => 'hero, features, intro, services, benefits, posts, cta, contact',
			'topic'   => 'hero, intro, services or posts, faq, cta',
			'about'   => 'hero, intro, features, benefits, cta',
			'contact' => 'hero, contact, faq',
		);
		$job = array(
			'page_type'      => self::kinds()[ $m['kind'] ],
			'topic'          => $m['topic'],
			'focus_keyword'  => $m['keyword'],
			'facts_from_owner' => $m['facts'],
			'editor_notes'   => $m['notes'],
			'contact_details_known' => array_filter( self::contact_info() ) ? true : false,
			'site_pages'     => array_slice( $pages, 0, 60 ),
			'block_library'  => $lib,
			'typical_order'  => $suggest[ $m['kind'] ],
			'icons_allowed'  => self::icons(),
		);
		if ( $src ) {
			$job['existing_page_to_redesign'] = $src;
		}
		$user = 'Design a ' . $job['page_type'] . ' as a sequence of blocks from block_library (use each block at most once; 5-9 blocks; follow typical_order unless the content needs otherwise). '
			. 'Write every text for real visitors, persuasive but honest. Use ONLY facts_from_owner'
			. ( $src ? ' and the existing page text' : '' ) . ' for specific facts (numbers, years, prices, names, guarantees); otherwise write [[REVIEW: …]]. '
			. 'Buttons are 1-3 words. Return JSON {"title":"page title (H1, ≤ 60 chars)","seo":{"seo_title":"≤ 60 chars","meta_description":"120-155 chars","slug":"short-slug","keywords":["focus first"]},'
			. '"blocks":[{"type":"hero","title":"...","text":"...","button":"..."},{"type":"features","title":"...","items":[{"icon":"check","title":"...","text":"..."}]},{"type":"services","title":"...","items":[{"page_id":123,"title":"...","text":"..."}]},{"type":"intro","title":"...","text":"<p>...</p>"}, …]} for: '
			. wp_json_encode( $job, JSON_UNESCAPED_UNICODE );
		$r = SSAI_AI_Client::chat_json( SSAI_Studio::system( $m ), $user );
		if ( is_wp_error( $r ) ) {
			wp_send_json_error( array( 'message' => $r->get_error_message() ) );
		}
		$blocks = self::clean_blocks( isset( $r['blocks'] ) ? $r['blocks'] : array(), true );
		if ( ! $blocks ) {
			wp_send_json_error( array( 'message' => 'هوش مصنوعی ساختار معتبری برنگرداند؛ دوباره امتحان کنید.' ) );
		}
		// Keep the images already chosen for blocks of the same type.
		$old = array();
		foreach ( $m['blocks'] as $b ) {
			$old[ $b['type'] ] = $b;
		}
		foreach ( $blocks as $i => $b ) {
			if ( isset( $old[ $b['type'] ] ) ) {
				$blocks[ $i ]['image']  = $old[ $b['type'] ]['image'];
				$blocks[ $i ]['images'] = $old[ $b['type'] ]['images'];
			}
			if ( 'contact' === $b['type'] ) {
				$blocks[ $i ]['map']  = 1;
				$blocks[ $i ]['form'] = 1;
			}
		}
		$m['blocks'] = $blocks;
		$m['title']  = isset( $r['title'] ) ? sanitize_text_field( (string) $r['title'] ) : $m['topic'];
		$seo         = isset( $r['seo'] ) && is_array( $r['seo'] ) ? $r['seo'] : array();
		$m['seo']    = array(
			'seo_title' => isset( $seo['seo_title'] ) ? sanitize_text_field( (string) $seo['seo_title'] ) : '',
			'meta'      => isset( $seo['meta_description'] ) ? sanitize_textarea_field( (string) $seo['meta_description'] ) : '',
			'slug'      => isset( $seo['slug'] ) ? sanitize_title( (string) $seo['slug'] ) : '',
			'keywords'  => array_slice( array_values( array_filter( array_map( 'sanitize_text_field', array_map( 'strval', isset( $seo['keywords'] ) && is_array( $seo['keywords'] ) ? $seo['keywords'] : array() ) ) ) ), 0, 6 ),
		);
		$m['status'] = 'outline';
		$m           = SSAI_Studio::store( $m );
		wp_send_json_success( array( 'item' => self::out( SSAI_Studio::item( $m['id'] ) ), 'message' => 'طرح صفحه آماده است؛ بلوک‌ها را مرتب و متن‌ها را بررسی کنید، عکس‌ها را انتخاب و بعد «ساخت پیش‌نویس» را بزنید.' ) );
	}

	/** Build the Elementor / Avada draft (a new draft every time unless the last one is still a draft). */
	public static function ajax_build() {
		SSAI_Studio::guard();
		$m = self::read_brief( SSAI_Studio::req_item() );
		if ( ! $m['blocks'] ) {
			wp_send_json_error( array( 'message' => 'هنوز بلوکی ندارد.' ) );
		}
		if ( ! current_user_can( 'edit_pages' ) ) {
			wp_send_json_error( array( 'message' => 'اجازه ساخت برگه ندارید.' ), 403 );
		}
		$builders = self::builders();
		if ( ! isset( $builders[ $m['builder'] ] ) ) {
			wp_send_json_error( array( 'message' => 'صفحه‌ساز انتخاب‌شده (المنتور یا آوادا) روی این سایت فعال نیست.' ) );
		}
		if ( 'elementor' === $m['builder'] && ! self::containers_on() ) {
			wp_send_json_error( array( 'message' => 'قابلیت «Flexbox Container» المنتور خاموش است. در المنتور › تنظیمات › ویژگی‌ها (Features) آن را فعال کنید و دوباره بسازید.' ) );
		}
		$title = '' !== $m['title'] ? $m['title'] : $m['topic'];
		if ( $m['source_page'] ) {
			$title .= ' (طراحی جدید)';
		}
		$arr = array(
			'post_type'    => 'page',
			'post_status'  => 'draft',
			'post_title'   => $title,
			'post_author'  => get_current_user_id(),
			'post_content' => 'avada' === $m['builder'] ? self::avada( $m ) : self::preview_body( $m, false ),
		);
		if ( '' !== $m['seo']['slug'] && ! $m['source_page'] ) {
			$arr['post_name'] = $m['seo']['slug'];
		}
		$existing = $m['post_id'] && 'draft' === get_post_status( $m['post_id'] ) ? $m['post_id'] : 0;
		if ( $existing ) {
			$arr['ID'] = $existing;
			$pid       = wp_update_post( wp_slash( $arr ), true );
		} else {
			$pid = wp_insert_post( wp_slash( $arr ), true );
		}
		if ( is_wp_error( $pid ) ) {
			wp_send_json_error( array( 'message' => $pid->get_error_message() ) );
		}
		update_post_meta( $pid, SSAI_Studio::ITEM_PM, $m['id'] );
		if ( 'elementor' === $m['builder'] ) {
			delete_post_meta( $pid, 'fusion_builder_status' );
			update_post_meta( $pid, '_elementor_edit_mode', 'builder' );
			update_post_meta( $pid, '_elementor_template_type', 'wp-page' );
			if ( defined( 'ELEMENTOR_VERSION' ) ) {
				update_post_meta( $pid, '_elementor_version', ELEMENTOR_VERSION );
			}
			update_post_meta( $pid, '_wp_page_template', 'elementor_header_footer' );
			SSAI_Elementor::save_data( $pid, self::elementor( $m ) );
		} else {
			delete_post_meta( $pid, '_elementor_edit_mode' ); // A rebuild may switch from Elementor to Avada.
			delete_post_meta( $pid, '_elementor_data' );
			update_post_meta( $pid, 'fusion_builder_status', 'active' );
			if ( file_exists( get_template_directory() . '/100-width.php' ) ) {
				update_post_meta( $pid, '_wp_page_template', '100-width.php' );
			}
		}
		// FAQ block → FAQPage structured data (stored as a custom schema of this page).
		foreach ( $m['blocks'] as $b ) {
			if ( 'faq' === $b['type'] && $b['items'] ) {
				$qa = array();
				foreach ( $b['items'] as $it ) {
					if ( '' !== $it['title'] && '' !== trim( wp_strip_all_tags( $it['text'] ) ) ) {
						$qa[] = array( '@type' => 'Question', 'name' => $it['title'], 'acceptedAnswer' => array( '@type' => 'Answer', 'text' => wp_strip_all_tags( $it['text'] ) ) );
					}
				}
				if ( $qa ) {
					update_post_meta( $pid, '_ssai_schema_custom', wp_slash( array( array( '@type' => 'FAQPage', 'mainEntity' => $qa ) ) ) );
				}
			}
		}
		if ( '' !== $m['seo']['seo_title'] ) {
			SSAI_Content::set_seo_title( $pid, $m['seo']['seo_title'] );
		}
		if ( '' !== $m['seo']['meta'] ) {
			SSAI_Content::set_meta_description( $pid, $m['seo']['meta'] );
		}
		$kws = $m['seo']['keywords'] ? $m['seo']['keywords'] : array_filter( array( $m['keyword'] ) );
		if ( $kws ) {
			SSAI_Content::set_focus_keyword( $pid, implode( ',', $kws ) );
		}
		$m['post_id'] = $pid;
		$m['status']  = 'draft';
		SSAI_Studio::store( $m );
		$msg = 'پیش‌نویس ' . $builders[ $m['builder'] ] . ' ساخته شد' . ( $m['source_page'] ? ' (صفحه اصلی دست نخورد)' : '' ) . '. در صفحه‌ساز باز کنید، علامت‌های «نیاز به بررسی» را تکمیل کنید و خودتان منتشر کنید.';
		wp_send_json_success( array( 'item' => self::out( SSAI_Studio::item( $m['id'] ) ), 'message' => $msg ) );
	}

	private static function containers_on() {
		if ( class_exists( '\Elementor\Plugin' ) && isset( \Elementor\Plugin::$instance->experiments ) ) {
			return \Elementor\Plugin::$instance->experiments->is_feature_active( 'container' );
