/**
 * Page designer: the AI picks blocks from a fixed library and writes their texts; the editor reorders and edits
 * them, picks images, and the plugin builds an editable Elementor (Flexbox containers) or Avada Builder draft
 * that follows the site's global colours and fonts.
 */
class SSAI_Designer {

	public static function init() {
		foreach ( array( 'plan', 'save', 'get', 'build' ) as $a ) {
			add_action( 'wp_ajax_ssai_ds_' . $a, array( __CLASS__, 'ajax_' . $a ) );
		}
	}

