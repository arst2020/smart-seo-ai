	public static function icons() {
		return array( 'check', 'star', 'heart', 'shield-alt', 'clock', 'user-md', 'tooth', 'smile', 'award', 'phone', 'map-marker-alt', 'calendar-check', 'hand-holding-heart', 'thumbs-up', 'cogs', 'tools', 'truck', 'leaf', 'lightbulb', 'comments', 'gem', 'bolt', 'lock', 'chart-line', 'user-friends', 'stethoscope', 'brain', 'home', 'graduation-cap', 'shopping-cart' );
	}

	public static function builders() {
		$out = array();
		if ( SSAI_Elementor::active() ) {
			$out['elementor'] = 'المنتور';
		}
		if ( SSAI_Avada::active() ) {
			$out['avada'] = 'آوادا (Avada Builder)';
		}
