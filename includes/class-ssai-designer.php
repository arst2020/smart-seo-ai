	private static function g( $color = '', $typo = '', $color_key = 'title_color', $typo_key = 'typography_typography' ) {
		$g = array();
		if ( $color ) {
			$g[ $color_key ] = 'globals/colors?id=' . $color;
		}
		if ( $typo ) {
			$g[ $typo_key ] = 'globals/typography?id=' . $typo;
		}
		return $g;
	}

	private static function box( $children, $s = array(), $inner = false ) {
		$base = array(
			'content_width'  => $inner ? 'full' : 'boxed',
			'flex_direction' => 'column',
			'flex_gap'       => array( 'unit' => 'px', 'size' => 20, 'column' => '20', 'row' => '20' ),
		);
		if ( ! $inner ) {
			$base['padding'] = array( 'unit' => 'px', 'top' => '64', 'right' => '20', 'bottom' => '64', 'left' => '20', 'isLinked' => false );
			$base['padding_mobile'] = array( 'unit' => 'px', 'top' => '40', 'right' => '16', 'bottom' => '40', 'left' => '16', 'isLinked' => false );
		}
		return array(
			'id'       => SSAI_Studio::el_id(),
			'elType'   => 'container',
			'isInner'  => $inner,
			'settings' => array_merge( $base, $s ),
			'elements' => array_values( array_filter( $children ) ),
		);
	}

	private static function w( $type, $s ) {
		return array( 'id' => SSAI_Studio::el_id(), 'elType' => 'widget', 'widgetType' => $type, 'settings' => $s, 'elements' => array() );
	}

	private static function heading( $text, $tag = 'h2', $align = 'center' ) {
		if ( '' === $text ) {
			return null;
		}
		return self::w( 'heading', array( 'title' => esc_html( $text ), 'header_size' => $tag, 'align' => $align, '__globals__' => self::g( 'primary', 'h1' === $tag ? 'primary' : ( 'h3' === $tag ? 'secondary' : 'primary' ) ) ) );
	}

	private static function text( $html, $align = '' ) {
		if ( '' === trim( wp_strip_all_tags( $html ) ) ) {
			return null;
		}
		$s = array( 'editor' => false === stripos( $html, '<p' ) && false === stripos( $html, '<ul' ) ? '<p>' . $html . '</p>' : $html, '__globals__' => self::g( 'text', 'text', 'text_color' ) );
		if ( $align ) {
			$s['align'] = $align;
		}
		return self::w( 'text-editor', $s );
	}

	private static function button( $label, $url, $align = 'center' ) {
		if ( '' === $label ) {
			return null;
		}
		return self::w( 'button', array( 'text' => $label, 'link' => array( 'url' => $url, 'is_external' => '', 'nofollow' => '' ), 'align' => $align, 'size' => 'md', '__globals__' => self::g( 'accent', 'accent', 'background_color' ) ) );
	}

	private static function image( $id ) {
		return $id ? self::w( 'image', array( 'image' => array( 'id' => $id, 'url' => self::img( $id, 'full' ), 'alt' => self::alt( $id ) ), 'image_size' => 'large', 'border_radius' => array( 'unit' => 'px', 'top' => '12', 'right' => '12', 'bottom' => '12', 'left' => '12', 'isLinked' => true ) ) ) : null;
	}

	private static function grid( $cards, $per_row = 3 ) {
		$w = array( 1 => 100, 2 => 48, 3 => 31, 4 => 23 );
		$out = array();
		foreach ( $cards as $c ) {
			$out[] = self::box(
				$c,
				array(
					'width'                 => array( 'unit' => '%', 'size' => $w[ max( 1, min( 4, $per_row ) ) ] ),
					'width_tablet'          => array( 'unit' => '%', 'size' => 48 ),
					'width_mobile'          => array( 'unit' => '%', 'size' => 100 ),
					'padding'               => array( 'unit' => 'px', 'top' => '24', 'right' => '24', 'bottom' => '24', 'left' => '24', 'isLinked' => true ),
					'background_background' => 'classic',
					'background_color'      => '#FFFFFF',
					'border_border'         => 'solid',
					'border_width'          => array( 'unit' => 'px', 'top' => '1', 'right' => '1', 'bottom' => '1', 'left' => '1', 'isLinked' => true ),
					'border_color'          => '#E6E8EC',
					'border_radius'         => array( 'unit' => 'px', 'top' => '12', 'right' => '12', 'bottom' => '12', 'left' => '12', 'isLinked' => true ),
				),
				true
			);
		}
		return self::box( $out, array( 'flex_direction' => 'row', 'flex_wrap' => 'wrap', 'justify_content' => 'center' ), true );
	}

	private static function elementor( $m ) {
		$data = array();
		$cta  = self::cta_link();
		foreach ( $m['blocks'] as $i => $b ) {
			$alt = $i > 0 && 0 === $i % 2 ? array( 'background_background' => 'classic', 'background_color' => '#F6F8FB' ) : array(); // Hero is tinted, then every other block.
			$t   = 'hero' === $b['type'] && '' === $b['title'] ? $m['title'] : $b['title'];
			switch ( $b['type'] ) {
				case 'hero':
				case 'intro':
					$col  = self::box(
						array(
							self::heading( $t, 'hero' === $b['type'] ? 'h1' : 'h2', 'start' ),
							'hero' === $b['type'] ? self::text( esc_html( $b['text'] ) ) : self::text( $b['text'] ),
							self::button( $b['button'], $cta, 'start' ),
						),
						array( 'width' => array( 'unit' => '%', 'size' => $b['image'] ? 55 : 100 ), 'width_mobile' => array( 'unit' => '%', 'size' => 100 ) ),
						true
					);
					$row  = array( $col );
					if ( $b['image'] ) {
						$row[] = self::box( array( self::image( $b['image'] ) ), array( 'width' => array( 'unit' => '%', 'size' => 45 ), 'width_mobile' => array( 'unit' => '%', 'size' => 100 ) ), true );
					}
					$data[] = self::box( $row, array_merge( array( 'flex_direction' => 'row', 'flex_wrap' => 'wrap', 'flex_align_items' => 'center' ), 'hero' === $b['type'] ? array( 'background_background' => 'classic', 'background_color' => '#F6F8FB', 'min_height' => array( 'unit' => 'vh', 'size' => 60 ) ) : $alt ) );
					break;
				case 'features':
				case 'services':
				case 'steps':
				case 'testimonials':
					$cards = array();
					foreach ( $b['items'] as $k => $it ) {
						if ( 'features' === $b['type'] ) {
							$cards[] = array( self::w( 'icon-box', array( 'selected_icon' => array( 'value' => 'fas fa-' . $it['icon'], 'library' => 'fa-solid' ), 'title_text' => $it['title'], 'description_text' => $it['text'], 'title_size' => 'h3', '__globals__' => self::g( 'primary', '', 'primary_color' ) ) ) );
						} elseif ( 'testimonials' === $b['type'] ) {
							$cards[] = array( self::text( '<p>«' . esc_html( $it['text'] ) . '»</p>' ), self::text( '<p><strong>' . esc_html( $it['title'] ) . '</strong></p>' ) );
						} else {
							$title   = 'steps' === $b['type'] ? number_format_i18n( $k + 1 ) . '. ' . $it['title'] : $it['title'];
							$link    = self::link_of( $it['link'] );
							$h       = self::heading( $title, 'h3', 'start' );
							if ( $h && $link ) {
								$h['settings']['link'] = array( 'url' => $link, 'is_external' => '', 'nofollow' => '' );
							}
							$cards[] = array( $h, self::text( esc_html( $it['text'] ) ), $link ? self::button( 'بیشتر بخوانید', $link, 'start' ) : null );
						}
					}
					$data[] = self::box( array( self::heading( $t ), self::grid( $cards, count( $cards ) >= 4 && 'services' !== $b['type'] ? 4 : 3 ) ), $alt );
					break;
				case 'benefits':
					$list = array();
					foreach ( $b['items'] as $it ) {
						$list[] = array( '_id' => SSAI_Studio::el_id(), 'text' => '' !== $it['text'] ? $it['text'] : $it['title'], 'selected_icon' => array( 'value' => 'fas fa-check-circle', 'library' => 'fa-solid' ) );
					}
					$data[] = self::box( array( self::heading( $t ), self::w( 'icon-list', array( 'icon_list' => $list, 'space_between' => array( 'unit' => 'px', 'size' => 12 ), '__globals__' => self::g( 'accent', '', 'icon_color' ) ) ) ), $alt );
					break;
				case 'faq':
					$tabs = array();
					foreach ( $b['items'] as $it ) {
						$tabs[] = array( '_id' => SSAI_Studio::el_id(), 'tab_title' => $it['title'], 'tab_content' => $it['text'] );
					}
					$data[] = self::box( array( self::heading( $t ), self::w( 'accordion', array( 'tabs' => $tabs, 'title_html_tag' => 'h3' ) ) ), $alt );
					break;
				case 'posts':
					$cards = array();
					foreach ( self::related_posts( $m ) as $p ) {
						$th      = get_post_thumbnail_id( $p );
						$h       = self::heading( get_the_title( $p ), 'h3', 'start' );
						$h['settings']['link'] = array( 'url' => get_permalink( $p ), 'is_external' => '', 'nofollow' => '' );
						$cards[] = array( self::image( $th ), $h, self::text( esc_html( wp_trim_words( get_the_excerpt( $p ), 18 ) ) ) );
					}
					if ( $cards ) {
						$data[] = self::box( array( self::heading( $t ), self::grid( $cards, 3 ) ), $alt );
					}
					break;
				case 'gallery':
					$g = array();
					foreach ( $b['images'] as $iid ) {
						$g[] = array( 'id' => $iid, 'url' => self::img( $iid, 'full' ) );
					}
					$data[] = self::box( array( self::heading( $t ), $g ? self::w( 'image-gallery', array( 'wp_gallery' => $g, 'gallery_columns' => '3', 'gallery_columns_mobile' => '2', 'thumbnail_size' => 'medium_large', 'gallery_link' => 'file' ) ) : self::text( '<p><mark class="ssai-review">[نیاز به بررسی: عکس‌های گالری را انتخاب کنید]</mark></p>' ) ), $alt );
					break;
				case 'cta':
					$data[] = self::box(
						array(
							self::w( 'heading', array( 'title' => esc_html( $t ), 'header_size' => 'h2', 'align' => 'center', 'title_color' => '#FFFFFF', '__globals__' => self::g( '', 'primary' ) ) ),
							self::w( 'text-editor', array( 'editor' => '<p>' . esc_html( $b['text'] ) . '</p>', 'align' => 'center', 'text_color' => '#FFFFFF' ) ),
							self::button( $b['button'], $cta ),
						),
						array( 'flex_align_items' => 'center', 'background_background' => 'classic', '__globals__' => array( 'background_color' => 'globals/colors?id=primary' ) )
					);
					break;
				case 'contact':
					$left = array( self::heading( $t, 'h2', 'start' ), self::text( $b['text'] ), self::text( self::contact_html( $b ) ) );
					if ( $b['form'] ) {
						if ( '' !== $m['form_code'] ) {
							$left[] = self::w( 'shortcode', array( 'shortcode' => $m['form_code'] ) );
						} elseif ( defined( 'ELEMENTOR_PRO_VERSION' ) ) {
							$left[] = self::w(
								'form',
								array(
									'form_name'   => 'تماس',
									'form_fields' => array(
										array( '_id' => SSAI_Studio::el_id(), 'custom_id' => 'name', 'field_type' => 'text', 'field_label' => 'نام', 'placeholder' => 'نام شما', 'required' => 'true', 'width' => '50' ),
										array( '_id' => SSAI_Studio::el_id(), 'custom_id' => 'phone', 'field_type' => 'tel', 'field_label' => 'تلفن', 'placeholder' => 'شماره تماس', 'required' => 'true', 'width' => '50' ),
										array( '_id' => SSAI_Studio::el_id(), 'custom_id' => 'message', 'field_type' => 'textarea', 'field_label' => 'پیام', 'placeholder' => 'پیام شما', 'width' => '100' ),
									),
									'button_text' => 'ارسال',
									'submit_actions' => array( 'email' ),
									'success_message' => 'پیام شما ارسال شد.',
								)
							);
						} else {
							$left[] = self::button( 'تماس با ما', $cta, 'start' );
						}
					}
					$row = array( self::box( $left, array( 'width' => array( 'unit' => '%', 'size' => $b['map'] ? 48 : 100 ), 'width_mobile' => array( 'unit' => '%', 'size' => 100 ) ), true ) );
					if ( $b['map'] ) {
						$row[] = self::box( array( self::w( 'google_maps', array( 'address' => self::map_query(), 'zoom' => array( 'unit' => 'px', 'size' => 15 ), 'height' => array( 'unit' => 'px', 'size' => 360 ) ) ) ), array( 'width' => array( 'unit' => '%', 'size' => 48 ), 'width_mobile' => array( 'unit' => '%', 'size' => 100 ) ), true );
					}
					$data[] = self::box( $row, array_merge( array( 'flex_direction' => 'row', 'flex_wrap' => 'wrap' ), $alt ) );
					break;
			}
		}
		return $data;
	}

	/* ================================================================ Avada Builder (shortcodes) */

	private static function q( $s ) {
		return str_replace( array( '"', '[', ']' ), array( '&quot;', '&#91;', '&#93;' ), (string) $s );
	}

	private static function av_text( $s ) {
		return preg_replace( '/\[(\/?)(fusion_|awb_)/', '&#91;$1$2', (string) $s );
	}

	private static function av_container( $inner, $bg = '' ) {
		return '[fusion_builder_container type="flex" hundred_percent="no" padding_top="64px" padding_bottom="64px" padding_top_small="40px" padding_bottom_small="40px"' . ( $bg ? ' background_color="' . $bg . '"' : '' ) . '][fusion_builder_row]' . $inner . '[/fusion_builder_row][/fusion_builder_container]' . "\n";
	}

	private static function av_col( $inner, $type = '1_1', $card = false ) {
		$extra = $card ? ' padding_top="24px" padding_right="24px" padding_bottom="24px" padding_left="24px" background_color="var(--awb-color1)" border_sizes_top="1px" border_sizes_right="1px" border_sizes_bottom="1px" border_sizes_left="1px" border_color="var(--awb-color3)" border_radius_top_left="12px" border_radius_top_right="12px" border_radius_bottom_left="12px" border_radius_bottom_right="12px"' : '';
		return '[fusion_builder_column type="' . $type . '" layout="' . $type . '" align_self="auto" content_layout="column" type_small="1_1"' . $extra . ']' . $inner . '[/fusion_builder_column]';
	}

	private static function av_title( $t, $size = 2, $align = 'center' ) {
		return '' === $t ? '' : '[fusion_title title_type="text" size="' . (int) $size . '" content_align="' . $align . '"]' . self::av_text( esc_html( $t ) ) . '[/fusion_title]';
	}

	private static function av_p( $html ) {
		return '' === trim( wp_strip_all_tags( $html ) ) ? '' : '[fusion_text]' . self::av_text( false === stripos( $html, '<p' ) && false === stripos( $html, '<ul' ) ? '<p>' . $html . '</p>' : $html ) . '[/fusion_text]';
	}

	private static function av_button( $label, $url, $align = 'center' ) {
		return '' === $label ? '' : '[fusion_button link="' . esc_url( $url ) . '" color="default" size="large" alignment="' . $align . '"]' . self::av_text( esc_html( $label ) ) . '[/fusion_button]';
	}

	private static function av_image( $id ) {
		return $id ? '[fusion_imageframe image_id="' . (int) $id . '|large" style_type="none" align="center" borderradius="12px" alt="' . self::q( self::alt( $id ) ) . '"]' . esc_url( self::img( $id, 'large' ) ) . '[/fusion_imageframe]' : '';
	}

	private static function avada( $m ) {
		$out  = '';
		$cta  = self::cta_link();
		$cols = array( 1 => '1_1', 2 => '1_2', 3 => '1_3', 4 => '1_4' );
		foreach ( $m['blocks'] as $i => $b ) {
			$bg = ( $i > 0 && 0 === $i % 2 ) || 'hero' === $b['type'] ? 'var(--awb-color2)' : '';
			$t  = 'hero' === $b['type'] && '' === $b['title'] ? $m['title'] : $b['title'];
			switch ( $b['type'] ) {
				case 'hero':
				case 'intro':
					$body = self::av_title( $t, 'hero' === $b['type'] ? 1 : 2, 'left' ) . self::av_p( 'hero' === $b['type'] ? esc_html( $b['text'] ) : $b['text'] ) . self::av_button( $b['button'], $cta, 'left' );
					$out .= self::av_container( $b['image'] ? self::av_col( $body, '1_2' ) . self::av_col( self::av_image( $b['image'] ), '1_2' ) : self::av_col( $body ), $bg );
					break;
				case 'features':
					$boxes = '';
					foreach ( $b['items'] as $it ) {
						$boxes .= '[fusion_content_box title="' . self::q( $it['title'] ) . '" icon="fa-' . $it['icon'] . ' fas"]' . self::av_text( esc_html( $it['text'] ) ) . '[/fusion_content_box]';
					}
					$n    = max( 1, min( 4, count( $b['items'] ) ) );
					$out .= self::av_container( self::av_col( self::av_title( $t ) . '[fusion_content_boxes layout="icon-on-top" columns="' . $n . '" icon_align="center" title_size="3"]' . $boxes . '[/fusion_content_boxes]' ), $bg );
					break;
				case 'services':
				case 'steps':
				case 'testimonials':
					$n     = count( $b['items'] ) >= 4 && 'services' !== $b['type'] ? 4 : 3;
					$cards = '';
					foreach ( $b['items'] as $k => $it ) {
						if ( 'testimonials' === $b['type'] ) {
							$cards .= self::av_col( self::av_p( '<p>«' . esc_html( $it['text'] ) . '»</p><p><strong>' . esc_html( $it['title'] ) . '</strong></p>' ), $cols[ $n ], true );
							continue;
						}
						$title  = 'steps' === $b['type'] ? number_format_i18n( $k + 1 ) . '. ' . $it['title'] : $it['title'];
						$link   = self::link_of( $it['link'] );
						$cards .= self::av_col( self::av_title( $title, 3, 'left' ) . self::av_p( esc_html( $it['text'] ) ) . ( $link ? self::av_button( 'بیشتر بخوانید', $link, 'left' ) : '' ), $cols[ $n ], true );
					}
					$out .= self::av_container( self::av_col( self::av_title( $t ) ) . $cards, $bg );
					break;
				case 'benefits':
					$li = '';
					foreach ( $b['items'] as $it ) {
						$li .= '[fusion_li_item]' . self::av_text( esc_html( '' !== $it['text'] ? $it['text'] : $it['title'] ) ) . '[/fusion_li_item]';
					}
					$out .= self::av_container( self::av_col( self::av_title( $t ) . '[fusion_checklist icon="fa-check-circle fas" size="16px"]' . $li . '[/fusion_checklist]' ), $bg );
					break;
				case 'faq':
					$tg = '';
					foreach ( $b['items'] as $it ) {
						$tg .= '[fusion_toggle title="' . self::q( $it['title'] ) . '" open="no"]' . self::av_text( $it['text'] ) . '[/fusion_toggle]';
					}
					$out .= self::av_container( self::av_col( self::av_title( $t ) . '[fusion_accordion type="accordions" boxed_mode="yes" title_tag="h3"]' . $tg . '[/fusion_accordion]' ), $bg );
					break;
				case 'posts':
					$cards = '';
					foreach ( self::related_posts( $m ) as $p ) {
						$cards .= self::av_col( self::av_image( get_post_thumbnail_id( $p ) ) . self::av_title( get_the_title( $p ), 3, 'left' ) . self::av_p( esc_html( wp_trim_words( get_the_excerpt( $p ), 18 ) ) ) . self::av_button( 'ادامه مطلب', get_permalink( $p ), 'left' ), '1_3', true );
					}
					if ( $cards ) {
						$out .= self::av_container( self::av_col( self::av_title( $t ) ) . $cards, $bg );
					}
					break;
				case 'gallery':
					$gi = '';
					foreach ( $b['images'] as $iid ) {
						$gi .= '[fusion_gallery_image image="' . esc_url( self::img( $iid, 'full' ) ) . '" image_id="' . (int) $iid . '|full"][/fusion_gallery_image]';
					}
					$out .= self::av_container( self::av_col( self::av_title( $t ) . ( $gi ? '[fusion_gallery layout="grid" columns="3" lightbox="yes"]' . $gi . '[/fusion_gallery]' : self::av_p( '<p><mark class="ssai-review">[نیاز به بررسی: عکس‌های گالری را انتخاب کنید]</mark></p>' ) ) ), $bg );
					break;
				case 'cta':
					$out .= self::av_container( self::av_col( self::av_title( $t ) . self::av_p( '<p style="text-align:center">' . esc_html( $b['text'] ) . '</p>' ) . self::av_button( $b['button'], $cta ) ), 'var(--awb-color3)' );
					break;
				case 'contact':
					$left = self::av_title( $t, 2, 'left' ) . self::av_p( $b['text'] ) . self::av_p( self::contact_html( $b ) );
					if ( $b['form'] ) {
						$left .= '' !== $m['form_code'] ? '[fusion_text]' . $m['form_code'] . '[/fusion_text]' : self::av_button( 'تماس با ما', $cta, 'left' );
					}
					if ( $b['map'] ) {
						$left .= self::av_button( 'مسیریابی در نقشه', 'https://www.google.com/maps/search/?api=1&query=' . rawurlencode( self::map_query() ), 'left' );
					}
					$out .= self::av_container( self::av_col( $left ), $bg );
					break;
			}
		}
		$out = preg_replace( '/\[\[\s*(?:REVIEW|بررسی|CHECK)\s*:?\s*(.*?)\]\]/iu', '[نیاز به بررسی: $1]', $out );
		return $out;
	}
