	private static function contact_html( $b ) {
		$c    = self::contact_info();
		$rows = array();
		if ( '' !== $c['phone'] ) {
			$rows[] = '📞 <a href="tel:' . esc_attr( preg_replace( '/[^\d+]/', '', $c['phone'] ) ) . '">' . esc_html( $c['phone'] ) . '</a>';
		}
		if ( '' !== $c['address'] ) {
			$rows[] = '📍 ' . esc_html( $c['address'] );
		}
		if ( '' !== $c['hours'] ) {
			$rows[] = '🕘 ' . esc_html( $c['hours'] );
		}
		if ( '' !== $c['email'] ) {
			$rows[] = '✉ <a href="mailto:' . esc_attr( $c['email'] ) . '">' . esc_html( $c['email'] ) . '</a>';
		}
		if ( ! $rows ) {
			$rows[] = '<mark class="ssai-review">[نیاز به بررسی: تلفن و آدرس را در «تنظیمات سئو › کسب‌وکار» وارد کنید یا این‌جا بنویسید]</mark>';
		}
		return '<p>' . implode( '<br>', $rows ) . '</p>';
	}

	private static function map_query() {
		$c = self::contact_info();
		return '' !== $c['lat'] && '' !== $c['lng'] ? $c['lat'] . ',' . $c['lng'] : ( '' !== $c['address'] ? $c['address'] : $c['name'] );
	}

