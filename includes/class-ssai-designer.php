		return '<div class="ssai-ds-page" style="--p:' . esc_attr( $c['primary'] ) . ';--a:' . esc_attr( $c['accent'] ) . ';--t:' . esc_attr( $c['text'] ) . '">' . self::preview_body( $m, true ) . '</div>';
	}

	/** Simple semantic HTML of the page (preview, and post_content fallback for search engines / analysis). */
	private static function preview_body( $m, $preview ) {
		$h   = '';
		$cta = self::cta_link();
		foreach ( $m['blocks'] as $i => $b ) {
			$cls = 'ssai-ds-b ssai-ds-' . $b['type'] . ( $i > 0 && 0 === $i % 2 ? ' is-alt' : '' );
			$h  .= '<section class="' . esc_attr( $cls ) . '">';
			$tag = 'hero' === $b['type'] ? 'h1' : 'h2';
			$t   = 'hero' === $b['type'] && '' === $b['title'] ? $m['title'] : $b['title'];
			$img = self::img( $b['image'] );
			switch ( $b['type'] ) {
				case 'hero':
				case 'intro':
					$h .= '<div class="ssai-ds-row"><div class="ssai-ds-col">' . ( '' !== $t ? "<$tag>" . esc_html( $t ) . "</$tag>" : '' ) . ( 'hero' === $b['type'] ? '<p class="ssai-ds-lead">' . esc_html( $b['text'] ) . '</p>' : $b['text'] );
					if ( '' !== $b['button'] ) {
						$h .= '<p><a class="ssai-ds-btn" href="' . esc_url( $cta ) . '">' . esc_html( $b['button'] ) . '</a></p>';
					}
					$h .= '</div>' . ( $img ? '<div class="ssai-ds-col"><img src="' . esc_url( $img ) . '" alt="' . esc_attr( self::alt( $b['image'] ) ) . '"></div>' : ( $preview ? '<div class="ssai-ds-col ssai-ds-noimg">🖼 عکس انتخاب نشده</div>' : '' ) ) . '</div>';
					break;
				case 'benefits':
					$h .= '<h2>' . esc_html( $t ) . '</h2><ul class="ssai-ds-check">';
					foreach ( $b['items'] as $it ) {
						$h .= '<li>' . esc_html( '' !== $it['text'] ? $it['text'] : $it['title'] ) . '</li>';
					}
					$h .= '</ul>';
					break;
				case 'faq':
					$h .= '<h2>' . esc_html( $t ) . '</h2>';
					foreach ( $b['items'] as $it ) {
						$h .= '<details><summary><h3>' . esc_html( $it['title'] ) . '</h3></summary>' . $it['text'] . '</details>';
					}
					break;
				case 'posts':
					$h .= '<h2>' . esc_html( $t ) . '</h2><div class="ssai-ds-grid">';
					foreach ( self::related_posts( $m ) as $p ) {
						$th = get_the_post_thumbnail_url( $p, 'medium' );
						$h .= '<div class="ssai-ds-card">' . ( $th ? '<img src="' . esc_url( $th ) . '" alt="">' : '' ) . '<h3><a href="' . esc_url( get_permalink( $p ) ) . '">' . esc_html( get_the_title( $p ) ) . '</a></h3><p>' . esc_html( wp_trim_words( get_the_excerpt( $p ), 18 ) ) . '</p></div>';
					}
					$h .= '</div>';
					break;
				case 'gallery':
					$h .= '<h2>' . esc_html( $t ) . '</h2><div class="ssai-ds-grid">';
					foreach ( $b['images'] as $iid ) {
						$h .= '<img src="' . esc_url( self::img( $iid, 'medium' ) ) . '" alt="' . esc_attr( self::alt( $iid ) ) . '">';
					}
					$h .= $b['images'] ? '' : ( $preview ? '<p class="ssai-ds-noimg">🖼 عکسی انتخاب نشده</p>' : '' );
					$h .= '</div>';
					break;
				case 'cta':
					$h .= '<h2>' . esc_html( $t ) . '</h2><p>' . esc_html( $b['text'] ) . '</p>' . ( '' !== $b['button'] ? '<p><a class="ssai-ds-btn" href="' . esc_url( $cta ) . '">' . esc_html( $b['button'] ) . '</a></p>' : '' );
					break;
				case 'contact':
					$h .= '<h2>' . esc_html( $t ) . '</h2>' . $b['text'] . self::contact_html( $b );
					if ( $b['map'] ) {
						$h .= '<p><a href="https://www.google.com/maps/search/?api=1&query=' . rawurlencode( self::map_query() ) . '">📍 مسیریابی در نقشه</a></p>';
					}
					if ( $b['form'] && $preview ) {
						$h .= '<p class="ssai-ds-noimg">' . esc_html( '' !== $m['form_code'] ? 'فرم: ' . $m['form_code'] : ( defined( 'ELEMENTOR_PRO_VERSION' ) && 'elementor' === $m['builder'] ? 'فرم تماس المنتور Pro (نام، تلفن، پیام)' : 'فرم: شورت‌کد فرم وارد نشده؛ فقط دکمه تماس گذاشته می‌شود' ) ) . '</p>';
					}
					break;
				default: // features, services, steps, testimonials.
					$h .= ( '' !== $t ? '<h2>' . esc_html( $t ) . '</h2>' : '' ) . '<div class="ssai-ds-grid">';
					foreach ( $b['items'] as $k => $it ) {
						$title = 'steps' === $b['type'] ? number_format_i18n( $k + 1 ) . '. ' . $it['title'] : $it['title'];
						$link  = self::link_of( $it['link'] );
						$h    .= '<div class="ssai-ds-card">' . ( 'features' === $b['type'] ? '<span class="ssai-ds-icon fas fa-' . esc_attr( $it['icon'] ) . '"></span>' : '' )
							. ( '' !== $it['title'] ? '<h3>' . ( $link ? '<a href="' . esc_url( $link ) . '">' . esc_html( $title ) . '</a>' : esc_html( $title ) ) . '</h3>' : '' )
							. '<p>' . esc_html( $it['text'] ) . '</p>' . ( 'testimonials' === $b['type'] && '' !== $it['title'] ? '' : '' ) . '</div>';
					}
					$h .= '</div>';
			}
			$h .= '</section>';
		}
		return SSAI_Studio::marks( preg_replace( '/\[نیاز به بررسی: (.*?)\]/u', '[[REVIEW: $1]]', $h ) );
	}

